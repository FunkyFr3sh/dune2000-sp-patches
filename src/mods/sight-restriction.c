const int num_circle_steps[8] = {1, 5, 21, 37, 61, 97, 137, 177};

// Custom implementation of function RevealCircle
DETOUR(0x0044E3B0, 0x0044E4C4, _Mod__RevealCircle);

void Mod__RevealCircle(int x, int y, unsigned char size)
{
  if ( size >= 8u )
  {
    DebugFatal("Map.cpp", "Shroud circles only defined up to size %d", 7);
  }

  bool step_restricted[177] = {false};
  for (int i = 0; i < num_circle_steps[size]; i++)
  {
    int mapx = x + circle_steps[i].x;
    int mapy = y + circle_steps[i].y;
    if (mapx < 0 || mapx >= gGameMap.width || mapy < 0 || mapy >= gGameMap.height)
      continue;
    // Previous step was restricted - mark also this step as restricted
    if (step_restricted[circle_steps[i].prev[0]] || step_restricted[circle_steps[i].prev[1]] || step_restricted[circle_steps[i].prev[2]])
    {
      step_restricted[i] = true;
      continue;
    }
    // Check this tile
    bool restricted = false;
    GameMapTileStruct *tile = &gGameMap.map[mapx + _CellNumbersWidthSpan[mapy]];
    int tile_index = tile->back_up_tile_index;
    if (circle_steps[i].y > 0 && circle_steps[i].x >= 0 && (tile_restrictions[tile_index] & (1 << 0)))
      restricted = true;
    if (circle_steps[i].y > 0 && circle_steps[i].x <= 0 && (tile_restrictions[tile_index] & (1 << 4)))
      restricted = true;
    if (circle_steps[i].x < 0 && circle_steps[i].y >= 0 && (tile_restrictions[tile_index] & (1 << 8)))
      restricted = true;
    if (circle_steps[i].x < 0 && circle_steps[i].y <= 0 && (tile_restrictions[tile_index] & (1 << 12)))
      restricted = true;
    if (circle_steps[i].y < 0 && circle_steps[i].x >= 0 && (tile_restrictions[tile_index] & (1 << 16)))
      restricted = true;
    if (circle_steps[i].y < 0 && circle_steps[i].x <= 0 && (tile_restrictions[tile_index] & (1 << 20)))
      restricted = true;
    if (circle_steps[i].x > 0 && circle_steps[i].y >= 0 && (tile_restrictions[tile_index] & (1 << 24)))
      restricted = true;
    if (circle_steps[i].x > 0 && circle_steps[i].y <= 0 && (tile_restrictions[tile_index] & (1 << 28)))
      restricted = true;
    step_restricted[i] = restricted;
    if (!restricted)
      tile->__shroud = 0;
  }

  RECT rect;
  rect.left = (x - size - 1) & ((x - size - 1 < 0) - 1);
  rect.top = (y - size - 1) & ((y - size - 1 < 0) - 1);
  rect.right = x + size + 2;
  rect.bottom = y + size + 2;
  UpdateShroudInRegion(&rect, gGameMap.width, gGameMap.height);
}
